  const ROARS = ['roar1', 'roar2', 'roar3'];

  /** { say, fx } audio keys for a picture id, or null (your own photos say nothing). */
  function lookup(id) {
    if (!id) return null;
    let m = /^m:(\d+)$/.exec(id);
    if (m) return { say: 'monster', fx: ROARS[Number(m[1]) % ROARS.length] };
    m = /^[fn]:(.+)$/.exec(id);
    const key = m ? m[1] : id.startsWith('s:') ? id : '@' + id;
    const row = PICS[key];
    if (!row) return null;
    const [say, fx] = row.split(' ');
    return { say, fx: fx || null };
  }

  /** Audio files for a picture, name first: ["audio/say/cat.mp3", "audio/fx/meow.mp3"]. */
  function urls(id) {
    const e = lookup(id);
    if (!e) return [];
    const list = [`audio/say/${e.say}.mp3`];
    if (e.fx) list.push(`audio/fx/${e.fx}.mp3`);
    return list;
  }

  PK.speech = { SAY, FX, PICS, ROARS, lookup, urls };
